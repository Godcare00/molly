#!/usr/bin/env bash
#
# setup-android-build.sh — user-local Android build toolchain for the Molly
# Expo SDK 54 / React Native 0.81.5 app.
#
# Installs ONLY what is necessary, entirely under $HOME (no sudo / no root):
#
#   JDK 17            -> ~/.local/opt/jdk-17        (kotlin.jvmToolchain(17), AGP 8.11)
#   Node 22 LTS       -> ~/.local/opt/node          (RN 0.81 requires Node >= 20.19.4)
#   Android cmdline-tools + platform-tools, platforms;android-36,
#   build-tools;36.0.0, ndk;27.1.12297006, cmake;3.22.1 -> ~/Android/Sdk
#
# Gradle is NOT installed on purpose: the Gradle *wrapper* generated by
# `npx expo prebuild` downloads the exact required Gradle 8.14.3 itself.
# (The distro's `gradle` package is 4.4.1 and is far too old — never use it.)
#
# Usage:  ./setup-android-build.sh
# Re-runnable: every step is skipped if already done.
#
set -euo pipefail

# ---------------------------------------------------------------- config ----
TOOLS_PREFIX="${TOOLS_PREFIX:-$HOME/.local/opt}"
ANDROID_HOME="${ANDROID_HOME:-$HOME/Android/Sdk}"
ENV_FILE="$HOME/.android-env.sh"
DL_DIR="${DL_DIR:-${TMPDIR:-/tmp}/android-build-setup}"

# Pinned versions (verified against the RN 0.81.5 / Expo SDK 54 templates)
JDK_URL="https://github.com/adoptium/temurin17-binaries/releases/download/jdk-17.0.20.1%2B1/OpenJDK17U-jdk_x64_linux_hotspot_17.0.20.1_1.tar.gz"
NODE_VER="v22.23.3"
CLT_BUILD="13114758"   # Android command-line tools 19.0

SDK_PKGS=(
  "platform-tools"
  "platforms;android-36"
  "build-tools;36.0.0"
  "ndk;27.1.12297006"
  "cmake;3.22.1"
)

# ------------------------------------------------------------------ util ----
log()  { printf '\033[1;36m==>\033[0m %s\n' "$*"; }
warn() { printf '\033[1;33m[!]\033[0m %s\n' "$*"; }
die()  { printf '\033[1;31m[x]\033[0m %s\n' "$*" >&2; exit 1; }

fetch() { # fetch <url> <dest>  (atomic: partial downloads never count as done)
  local url="$1" dest="$2"
  if [ -s "$dest" ]; then log "cached $(basename "$dest")"; return 0; fi
  log "downloading $(basename "$dest")"
  rm -f "$dest.part"
  curl -fL --retry 3 --retry-delay 2 -o "$dest.part" "$url" \
    || { rm -f "$dest.part"; die "download failed: $url"; }
  mv "$dest.part" "$dest"
}

[ "$(uname -m)" = "x86_64" ] || die "this script assumes x86_64, got $(uname -m)"
for c in curl tar unzip; do command -v "$c" >/dev/null || die "missing required tool: $c"; done
mkdir -p "$TOOLS_PREFIX" "$ANDROID_HOME/cmdline-tools" "$DL_DIR"

# --------------------------------------------------------------- 1. JDK 17 ----
JDK_LINK="$TOOLS_PREFIX/jdk-17"
if [ -x "$JDK_LINK/bin/java" ]; then
  log "JDK 17 already present -> $JDK_LINK"
else
  fetch "$JDK_URL" "$DL_DIR/jdk17.tar.gz"
  log "extracting JDK 17"
  tar xzf "$DL_DIR/jdk17.tar.gz" -C "$TOOLS_PREFIX"
  rm -rf "$JDK_LINK"
  mv "$TOOLS_PREFIX"/jdk-17.0.* "$JDK_LINK" 2>/dev/null || true
  [ -x "$JDK_LINK/bin/java" ] || die "JDK extraction failed"
fi
export JAVA_HOME="$JDK_LINK"
export PATH="$JAVA_HOME/bin:$PATH"

# ------------------------------------------------------------- 2. Node LTS ----
NODE_LINK="$TOOLS_PREFIX/node"
node_ok=false
if command -v node >/dev/null 2>&1; then
  cur="$(node -v | sed 's/^v//')"
  # compare major.minor.patch against 20.19.4
  if [ "$(printf '%s\n20.19.4\n' "$cur" | sort -V | head -1)" = "20.19.4" ]; then node_ok=true; fi
fi
if [ "$node_ok" = true ]; then
  log "Node $(node -v) already satisfies >= 20.19.4"
else
  fetch "https://nodejs.org/dist/${NODE_VER}/node-${NODE_VER}-linux-x64.tar.gz" "$DL_DIR/node.tar.gz"
  log "extracting Node ${NODE_VER}"
  tar xzf "$DL_DIR/node.tar.gz" -C "$TOOLS_PREFIX"
  rm -rf "$NODE_LINK"
  mv "$TOOLS_PREFIX/node-${NODE_VER}-linux-x64" "$NODE_LINK"
fi
export PATH="$NODE_LINK/bin:$PATH"

# ------------------------------------------------- 3. Android cmdline-tools ----
SDKMANAGER="$ANDROID_HOME/cmdline-tools/latest/bin/sdkmanager"
if [ -x "$SDKMANAGER" ]; then
  log "cmdline-tools already present"
else
  fetch "https://dl.google.com/android/repository/commandlinetools-linux-${CLT_BUILD}_latest.zip" "$DL_DIR/cmdline-tools.zip"
  log "extracting cmdline-tools"
  rm -rf "$DL_DIR/clt" "$ANDROID_HOME/cmdline-tools/latest"
  unzip -q "$DL_DIR/cmdline-tools.zip" -d "$DL_DIR/clt"
  mv "$DL_DIR/clt/cmdline-tools" "$ANDROID_HOME/cmdline-tools/latest"
fi

export ANDROID_HOME ANDROID_SDK_ROOT="$ANDROID_HOME"
export PATH="$ANDROID_HOME/platform-tools:$ANDROID_HOME/cmdline-tools/latest/bin:$PATH"

# --------------------------------------------- 4. SDK packages + licenses ----
log "accepting SDK licenses"
yes | "$SDKMANAGER" --sdk_root="$ANDROID_HOME" --licenses >/dev/null 2>&1 || true

log "installing SDK packages: ${SDK_PKGS[*]}"
"$SDKMANAGER" --sdk_root="$ANDROID_HOME" "${SDK_PKGS[@]}"

# ------------------------------------------------------ 5. shell env file ----
log "writing $ENV_FILE"
cat > "$ENV_FILE" <<EOF
# Android build toolchain (user-local) — generated by setup-android-build.sh
export JAVA_HOME="$TOOLS_PREFIX/jdk-17"
export ANDROID_HOME="$ANDROID_HOME"
export ANDROID_SDK_ROOT="\$ANDROID_HOME"
export PATH="$TOOLS_PREFIX/node/bin:\$JAVA_HOME/bin:\$ANDROID_HOME/cmdline-tools/latest/bin:\$ANDROID_HOME/platform-tools:\$PATH"
EOF

for rc in "$HOME/.bashrc" "$HOME/.zshrc"; do
  [ -e "$rc" ] || continue
  if ! grep -q 'android-env.sh' "$rc"; then
    printf '\n# Android build toolchain\n[ -f "%s" ] && . "%s"\n' "$ENV_FILE" "$ENV_FILE" >> "$rc"
    log "sourced env in $rc"
  fi
done

# ------------------------------------------------------------ 6. verify ----
echo
log "verification"
printf 'java   : %s\n' "$("$JAVA_HOME/bin/java" -version 2>&1 | head -1)"
printf 'node   : %s\n' "$("$NODE_LINK/bin/node" -v)"
printf 'npm    : %s\n' "$("$NODE_LINK/bin/npm" -v)"
printf 'adb    : %s\n' "$("$ANDROID_HOME/platform-tools/adb" version | head -1)"
"$SDKMANAGER" --sdk_root="$ANDROID_HOME" --list_installed 2>/dev/null | sed -n '/Installed packages/,$p' | head -15

cat <<EOF

--------------------------------------------------------------
Done. Start a new shell (or: . "$ENV_FILE") to pick up the env.

Gradle needs no install — the wrapper pulls it in automatically:
    cd ~/Desktop/molly/molly-app
    npx expo prebuild --platform android
    cd android && ./gradlew --version      # should report Gradle 8.14.3
    ./gradlew assembleDebug                # first build; slow on 4 cores
--------------------------------------------------------------
EOF
